const { test, before, after } = require('node:test');
const assert = require('node:assert/strict');
const http = require('node:http');

require('../helpers/testEnv');

const { supabase } = require('../../config/supabase');
const app = require('../../app');
const venue = require('../../services/venueService');

/**
 * A ROOM BIGGER THAN ONE PAGE OF POSTGREST.
 *
 * Supabase's Data API returns at most 1,000 rows per request (`max_rows`) and
 * says nothing when it stops. Both seat-map reads asked for every seat on the
 * map with no ORDER BY and no paging, so a 1,250-seat room came back as 1,000
 * seats — and WHICH 1,000 followed the physical order of the rows, which moves
 * every time a hold or a sale rewrites one. A buyer saw a different set of
 * empty chairs on each load: the seat map's own "sometimes it is there and
 * sometimes it is not".
 *
 * 25 tables of 50 seats. Seat stock is generated by save_venue_map, exactly as
 * an organizer drawing the room would.
 */
const TABLES = 25;
const SEATS_PER_TABLE = 50;
const TOTAL = TABLES * SEATS_PER_TABLE;

let server; let baseUrl;
const stamp = Date.now();
const ids = {};

before(async () => {
  server = http.createServer(app);
  await new Promise((r) => server.listen(0, '127.0.0.1', r));
  baseUrl = `http://127.0.0.1:${server.address().port}/api/v1`;

  const { data: profile } = await supabase.from('profiles').insert({
    email: `bigmap-${stamp}@eventsli-test.invalid`, full_name: 'Big Map', role: 'organizer',
  }).select('id').single();
  ids.profile = profile.id;

  const { data: org } = await supabase.from('organizers').insert({
    owner_user_id: profile.id, display_name: 'Big Room Co', country: 'CA',
  }).select('id').single();
  ids.organizer = org.id;

  const { data: terms } = await supabase.from('terms_versions')
    .select('id').eq('audience', 'organizer').eq('is_current', true).single();

  const { data: ev, error } = await supabase.from('events').insert({
    organizer_id: org.id, slug: `bigmap-${stamp}`, title: 'Big Room Test',
    country: 'CA', timezone: 'America/Toronto',
    starts_at: new Date(Date.now() + 40 * 86400e3).toISOString(),
    ends_at: new Date(Date.now() + 40 * 86400e3 + 3600e3).toISOString(),
    currency: 'CAD', status: 'published', terms_accepted_id: terms.id,
    purchase_mode: 'seat_and_table',
  }).select('id, slug').single();
  if (error) throw new Error(`seed: ${error.message}`);
  ids.event = ev.id;
  ids.slug = ev.slug;

  const tables = Array.from({ length: TABLES }, (_, i) => ({
    label: `T${String(i + 1).padStart(2, '0')}`, seatCount: SEATS_PER_TABLE,
    priceCents: null, seatPriceCents: 4500, isPrivate: false,
    position: { x: (i % 5) * 120, y: Math.floor(i / 5) * 120, rotation: 0 }, shape: 'round',
  }));
  const saved = await venue.saveMap(ids.event, { layout: { width: 800 }, tables });
  ids.map = saved.mapId;

  const { count } = await supabase.from('seats')
    .select('id', { count: 'exact', head: true }).eq('venue_map_id', ids.map);
  assert.equal(count, TOTAL, 'the room really has more seats than one page');
});

after(async () => {
  if (ids.map) {
    await supabase.from('seats').delete().eq('venue_map_id', ids.map);
    await supabase.from('tables').delete().eq('venue_map_id', ids.map);
    await supabase.from('venue_maps').delete().eq('id', ids.map);
  }
  if (ids.event) await supabase.from('events').delete().eq('id', ids.event);
  if (ids.organizer) await supabase.from('organizers').delete().eq('id', ids.organizer);
  if (ids.profile) await supabase.from('profiles').delete().eq('id', ids.profile);
  await new Promise((r) => server.close(r));
});

test('REGRESSION: a buyer sees every seat in a room of more than 1,000', async () => {
  const res = await fetch(`${baseUrl}/public/events/${ids.slug}/seat-map`);
  const body = await res.json();
  assert.equal(res.status, 200, JSON.stringify(body).slice(0, 300));
  assert.equal(body.data.seats.length, TOTAL, 'not one page of them');
  assert.equal(new Set(body.data.seats.map((s) => s.id)).size, TOTAL, 'and no seat twice');
});

test('REGRESSION: the organizer\'s editor gets every seat too', async () => {
  const map = await venue.getMapForOrganizer(ids.event);
  const seats = map.tables.reduce((n, t) => n + t.seats.length, 0) + map.looseSeats.length;
  assert.equal(seats, TOTAL);
  for (const t of map.tables) assert.equal(t.seats.length, SEATS_PER_TABLE, `${t.label} is whole`);
});

test('the same seats come back on every load, in the same order', async () => {
  // Rewrite some rows so their physical order changes, as holds and sales do.
  const { data: some } = await supabase.from('seats')
    .select('id').eq('venue_map_id', ids.map).order('id').limit(300);
  await supabase.from('seats').update({ row_label: 'R' }).in('id', some.map((s) => s.id));

  const a = await (await fetch(`${baseUrl}/public/events/${ids.slug}/seat-map`)).json();
  const b = await (await fetch(`${baseUrl}/public/events/${ids.slug}/seat-map`)).json();
  assert.deepEqual(a.data.seats.map((s) => s.id), b.data.seats.map((s) => s.id));
});
