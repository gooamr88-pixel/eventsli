#!/usr/bin/env node
/**
 * ═══════════════════════════════════════════════════════════════════════════
 * Draws the Eventsli logo's vector source: the E-ticket mark
 * (`components/brand/markPath.js`) and the wordmark
 * (`components/brand/wordmarkPath.js`).
 *
 *   npm install --no-save opentype.js@1.3.4    # once; not an app dependency
 *   node scripts/brandLogo.js
 *
 * Then run scripts/brandIcons.js and scripts/brandKit.js, which render every
 * PNG and the print kit FROM the two files this writes.
 *
 * THE E-TICKET, chosen by the owner on 2026-11-15 over a pin and a stage mark,
 * "more professional" than the playful marks it was compared with: a yellow
 * ticket — a rounded square with a notch in each side — with a near-black E in
 * it. The E's middle bar points at the right-hand notch, so the initial and the
 * product are one shape. The word beside it is Nunito Black (the owner found
 * Montserrat "very formal"): rounded terminals that echo the ticket's corners,
 * friendly without being a toy.
 *
 * DRAWN, not traced: rectangles, quarter-circle corners and two half-circle
 * notches on a 460-unit grid, exact at 16px and at 2,000. The word is outlined
 * from Nunito Black — the face the site's headings are set in — so the paths
 * render identically on a machine without the font.
 * ═══════════════════════════════════════════════════════════════════════════ */
const fs = require('node:fs');
const path = require('node:path');

const BRAND = path.join(__dirname, '..', 'src', 'app', 'components', 'brand');

/* ── The mark: a 460 × 460 grid ──────────────────────────────────────────── */

const SIZE = 460;
const CORNER = 100;          // the ticket's corner radius
const NOTCH = 50;            // the radius of the notch in each side
const MID = SIZE / 2;

/** The ticket: four rounded corners, a half-circle bitten out of each side. */
function ticket() {
  const s = SIZE; const c = CORNER; const n = NOTCH; const m = MID;
  return `M${c} 0H${s - c}A${c} ${c} 0 0 1 ${s} ${c}V${m - n}A${n} ${n} 0 0 0 ${s} ${m + n}`
    + `V${s - c}A${c} ${c} 0 0 1 ${s - c} ${s}H${c}A${c} ${c} 0 0 1 0 ${s - c}`
    + `V${m + n}A${n} ${n} 0 0 0 0 ${m - n}V${c}A${c} ${c} 0 0 1 ${c} 0Z`;
}

/**
 * The E: a 60-unit stem and three 55-unit bars. Top and bottom reach 330; the
 * middle bar stops short at 295, so its end sits in line with the right notch.
 */
function initial() {
  const x0 = 130; const stem = 60; const right = 330; const midRight = 295;
  const top = 115; const bottom = 345; const bar = 55;
  const midTop = MID - bar / 2; const midBottom = MID + bar / 2;
  const xs = x0 + stem;
  return `M${x0} ${top}H${right}V${top + bar}H${xs}V${midTop}H${midRight}V${midBottom}H${xs}`
    + `V${bottom - bar}H${right}V${bottom}H${x0}Z`;
}

/* ── The word ─────────────────────────────────────────────────────────────── */

async function nunito900(opentype) {
  // An unknown user agent gets TrueType, which opentype.js reads directly.
  const css = await (await fetch('https://fonts.googleapis.com/css2?family=Nunito:wght@900', { headers: { 'user-agent': 'curl/8.0' } })).text();
  const url = css.match(/url\((https:[^)]+)\)/)[1];
  return opentype.parse(await (await fetch(url)).arrayBuffer());
}

function buildWord(font) {
  const SIZE_PT = 140;                 // cap height ≈ 98 units
  const TRACK = -0.005 * SIZE_PT;      // a hair tight, as display type is set
  const scale = SIZE_PT / font.unitsPerEm;
  const glyphs = font.stringToGlyphs('Eventsli');
  let x = 0;
  const parts = glyphs.map((g, i) => {
    const p = g.getPath(x, 0, SIZE_PT);
    x += g.advanceWidth * scale + TRACK;
    if (i < glyphs.length - 1) x += font.getKerningValue(g, glyphs[i + 1]) * scale;
    return p;
  });

  let minX = Infinity; let minY = Infinity; let maxX = -Infinity; let maxY = -Infinity;
  for (const p of parts) {
    const b = p.getBoundingBox();
    minX = Math.min(minX, b.x1); minY = Math.min(minY, b.y1);
    maxX = Math.max(maxX, b.x2); maxY = Math.max(maxY, b.y2);
  }
  const d = (list) => list.map((p) => p.toPathData(1)).join('');
  const vb = [Math.floor(minX), Math.floor(minY), Math.ceil(maxX - Math.floor(minX)), Math.ceil(maxY - Math.floor(minY))];
  return { viewBox: vb.join(' '), events: d(parts.slice(0, 6)), li: d(parts.slice(6)) };
}

/* ── Write ────────────────────────────────────────────────────────────────── */

(async () => {
  const opentype = require('opentype.js');
  const word = buildWord(await nunito900(opentype));

  fs.writeFileSync(path.join(BRAND, 'markPath.js'), `/**
 * The Eventsli mark — the E-ticket — as vector path data, on a ${SIZE}-unit grid.
 *
 * GENERATED by scripts/brandLogo.js; change the geometry there and re-run it
 * rather than editing numbers here. Chosen by the owner on 2026-11-15: a yellow
 * ticket (a rounded square with a notch in each side) carrying a near-black E.
 *
 * TWO SHAPES, TWO COLOURS. \`MARK_FRAME\` is the ticket (\`--es-logo-mark\`, the
 * sheet's yellow); \`MARK_INITIAL\` is the E painted over it (\`--es-logo-initial\`,
 * near-black). The E is a shape rather than a hole, so on a dark ground it stays
 * near-black on yellow instead of showing the ground through the ticket.
 *
 * Read by things that must agree: \`Logo.jsx\`, \`app/icon.svg\` (the favicon,
 * which never sees a stylesheet so it carries the paths literally), the QR
 * centre (\`landing/brandQr.js\`) and \`scripts/brandIcons.js\`, which renders
 * every PNG icon from them. \`test/logo.test.jsx\` fails if the favicon's copy
 * ever drifts from this one.
 */
export const MARK_VIEWBOX = '0 0 ${SIZE} ${SIZE}';

export const MARK_FRAME = '${ticket()}';

export const MARK_INITIAL = '${initial()}';
`);

  fs.writeFileSync(path.join(BRAND, 'wordmarkPath.js'), `/**
 * The Eventsli wordmark as vector path data.
 *
 * GENERATED by scripts/brandLogo.js from Nunito Black, the face the site's
 * headings are set in (2026-11-15). Rounded and friendly, echoing the ticket's
 * corners. Kept as paths, not text, so the word is the same on a
 * machine without the font and takes its colour from a CSS role.
 *
 * TWO EXPORTS, ONE COLOUR. The word is near-black throughout; it is two paths
 * ("Events" and "li") because the print kit and the tests address the halves,
 * and a two-colour treatment would need nothing but CSS.
 */
export const WORDMARK_VIEWBOX = '${word.viewBox}';

/** E, v, e, n, t, s. */
export const WORDMARK_EVENTS = '${word.events}';

/** l, i. */
export const WORDMARK_LI = '${word.li}';
`);

  console.log('brandLogo: mark 0 0', SIZE, SIZE, '· word', word.viewBox);
})().catch((err) => { console.error(err); process.exit(1); });
